def load_state():
    try:
        with open(STATE_FILE, "r", encoding="utf-8") as f: return json.load(f)
    except Exception:
        return {"used": [], "scheduled": [], "log": []}

def save_state(st):
    st["used"] = st.get("used", [])[-200:]; st["log"] = st.get("log", [])[-60:]
    with open(STATE_FILE, "w", encoding="utf-8") as f: json.dump(st, f, ensure_ascii=False, indent=1)

def pick_slot(state, min_gap_min=60):
    """Pick today's (or the next possible day's) publish time inside the window, different from the last video's time."""
    now = dt.datetime.utcnow()
    w0, w1 = WINDOW_UTC.split("-")
    start = int(w0.split(":")[0]) * 60 + int(w0.split(":")[1])
    end = int(w1.split(":")[0]) * 60 + int(w1.split(":")[1])
    marks = list(range(start, end + 1, 30))
    last_min = None
    try:
        lt = state["used"][-1]["at"]
        last_min = int(lt[11:13]) * 60 + int(lt[14:16])
    except Exception:
        pass
    for day in range(0, 4):
        base = (now + dt.timedelta(days=day)).replace(hour=0, minute=0, second=0, microsecond=0)
        cands = [m for m in marks if base + dt.timedelta(minutes=m) >= now + dt.timedelta(minutes=min_gap_min)]
        cands = [m for m in cands if m != last_min] or cands
        if cands:
            m = random.Random(base.strftime("%Y%m%d")).choice(cands)
            return (base + dt.timedelta(minutes=m)).strftime("%Y-%m-%dT%H:%M:%SZ")
    return (now + dt.timedelta(hours=2)).strftime("%Y-%m-%dT%H:%M:%SZ")

def yt_service():
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    from googleapiclient.discovery import build
    creds = Credentials(None, refresh_token=os.environ["YT_REFRESH_TOKEN"], token_uri="https://oauth2.googleapis.com/token",
                        client_id=os.environ["YT_CLIENT_ID"], client_secret=os.environ["YT_CLIENT_SECRET"],
                        scopes=["https://www.googleapis.com/auth/youtube.upload", "https://www.googleapis.com/auth/youtube"])
    creds.refresh(Request())
    return build("youtube", "v3", credentials=creds, cache_discovery=False)

def upload(video, thumb, script, publish_at):
    from googleapiclient.http import MediaFileUpload
    yt = yt_service()
    hashtags = " ".join(script["hashtags"][:4])
    desc = (script["description"] + f"\n\n{hashtags} #Shorts #{CHANNEL}").strip()[:4900]
    tags = []
    total = 0
    for t in script["tags"] + [CHANNEL, "shorts"]:
        if total + len(t) + 1 > 450: break
        tags.append(t); total += len(t) + 1
    body = {"snippet": {"title": script["title"][:95], "description": desc, "tags": tags, "categoryId": "27", "defaultLanguage": "ar", "defaultAudioLanguage": "ar"},
            "status": {"privacyStatus": "private", "publishAt": publish_at, "selfDeclaredMadeForKids": False, "containsSyntheticMedia": True}}
    last = None
    for attempt in range(3):
        try:
            req = yt.videos().insert(part="snippet,status", body=body, media_body=MediaFileUpload(video, mimetype="video/mp4", chunksize=8 * 1024 * 1024, resumable=True))
            resp = None
            while resp is None:
                _, resp = req.next_chunk()
            vid = resp["id"]
            log("uploaded:", vid, "publishAt", publish_at)
            if thumb:
                try:
                    yt.thumbnails().set(videoId=vid, media_body=MediaFileUpload(thumb, mimetype="image/jpeg")).execute()
                except Exception as e:
                    log("thumbnail skipped:", e)
            return vid
        except Exception as e:
            last = e; log("upload retry:", e); time.sleep(10 * (attempt + 1))
    raise RuntimeError(f"upload failed: {last}")

# ───────────────────────── main ─────────────────────────
def main():
    args = sys.argv[1:]
    if args and args[0] == "assets":
        make_assets(); return
    dry = "--dry" in args or os.getenv("DRY_RUN") == "1"
    state = load_state()
    now_iso = dt.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
    pending = [x for x in state.get("scheduled", []) if x > now_iso]
    if pending and not dry and os.getenv("FORCE") != "1":
        log("a video is already scheduled for", pending, "- nothing to do")
        return
    script = write_script(state)
    log("TITLE:", script["title"])
    video, thumb, D = build_video(script)
    if dry:
        log("dry run done:", video); return
    slot = pick_slot(state)
    vid = upload(video, thumb, script, slot)
    state.setdefault("used", []).append({"topic": script["topic"], "title": script["title"], "id": vid, "at": slot})
    state.setdefault("scheduled", []).append(slot)
    cut = (dt.datetime.utcnow() - dt.timedelta(days=2)).strftime("%Y-%m-%dT%H:%M:%SZ")
    state["scheduled"] = [s for s in state["scheduled"] if s >= cut]
    state.setdefault("log", []).append({"t": dt.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"), "id": vid, "title": script["title"]})
    save_state(state)
    log("done")

if __name__ == "__main__":
    main()
