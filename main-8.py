# ───────────────────────── small helpers ─────────────────────────
def lerp(a, b, k): return a + (b - a) * k
def clamp(x, a=0.0, b=1.0): return max(a, min(b, x))
def eo3(k): k = clamp(k); return 1 - (1 - k) ** 3
def eob(k):
    k = clamp(k); c1 = 1.70158; c3 = c1 + 1
    return 1 + c3 * (k - 1) ** 3 + c1 * (k - 1) ** 2
def mixc(a, b, k): return tuple(int(lerp(a[i], b[i], clamp(k))) for i in range(3))
def shade(c, k):
    return tuple(int(v * k) for v in c) if k <= 1 else mixc(c, (255, 255, 255), k - 1)
def A(c, a): return (int(c[0]), int(c[1]), int(c[2]), int(255 * clamp(a)))
def log(*a): print(*a, flush=True)

