_BG = {}
def get_bg(pid):
    if pid in _BG:
        return _BG[pid]
    p = PALETTES[pid]
    w, h = W // 2, H // 2
    y = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    c1 = np.array(p["bg1"], dtype=np.float32)[None, None, :]
    c2 = np.array(p["bg2"], dtype=np.float32)[None, None, :]
    arr = c1 * (1 - y) + c2 * y
    arr = np.repeat(arr, w, axis=1)
    xs = np.linspace(-1, 1, w, dtype=np.float32)[None, :]
    ys = np.linspace(-1, 1, h, dtype=np.float32)[:, None]
    d = np.sqrt((xs * 0.95) ** 2 + (ys + 0.3) ** 2)
    g = (np.clip(1 - d, 0, 1) ** 2 * 0.55)[..., None]
    arr = arr + g * np.array(p["acc2"], dtype=np.float32)[None, None, :] * 0.30
    v = 1 - 0.45 * np.clip(d - 0.55, 0, 1)[..., None]
    arr = np.clip(arr * v, 0, 255).astype(np.uint8)
    im = Image.fromarray(arr).resize((W * SS, H * SS), Image.BICUBIC)
    _BG[pid] = im
    return im

