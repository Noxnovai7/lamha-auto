class Cv:
    def __init__(s, im):
        s.im = im
        s.d = ImageDraw.Draw(im, "RGBA")
    def circle(s, x, y, r, fill=None, outline=None, width=1):
        s.d.ellipse([(x - r) * SS, (y - r) * SS, (x + r) * SS, (y + r) * SS], fill=fill, outline=outline, width=max(1, int(width * SS)))
    def ellipse(s, x, y, rx, ry, fill=None, outline=None, width=1):
        s.d.ellipse([(x - rx) * SS, (y - ry) * SS, (x + rx) * SS, (y + ry) * SS], fill=fill, outline=outline, width=max(1, int(width * SS)))
    def rrect(s, x0, y0, x1, y1, r, fill=None, outline=None, width=1):
        s.d.rounded_rectangle([x0 * SS, y0 * SS, x1 * SS, y1 * SS], radius=r * SS, fill=fill, outline=outline, width=max(1, int(width * SS)))
    def poly(s, pts, fill=None, outline=None):
        s.d.polygon([(x * SS, y * SS) for x, y in pts], fill=fill, outline=outline)
    def line(s, pts, fill, width):
        s.d.line([(x * SS, y * SS) for x, y in pts], fill=fill, width=max(1, int(width * SS)), joint="curve")
    def arc(s, x, y, rx, ry, a0, a1, fill, width):
        s.d.arc([(x - rx) * SS, (y - ry) * SS, (x + rx) * SS, (y + ry) * SS], a0, a1, fill=fill, width=max(1, int(width * SS)))
    def text(s, x, y, text, size, fill, anchor="mm", stroke=0):
        draw_text(s.d, (x * SS, y * SS), text, size * SS, fill, anchor, stroke * SS)

def glow(cv, x, y, r, col, a=0.5, steps=7):
    for i in range(steps):
        k = i / steps
        cv.circle(x, y, r * (1 - k * 0.85), A(col, a * (0.08 + 0.18 * k)))

def sphere(cv, x, y, r, col, shadow=True):
    if shadow:
        cv.ellipse(x, y + r * 1.05, r * 0.95, r * 0.22, A((0, 0, 0), 0.28))
    n = 9
    for i in range(n):
        k = i / (n - 1)
        rr = r * (1 - 0.72 * k)
        c = mixc(shade(col, 0.55), shade(col, 1.45), k)
        cv.circle(x - r * 0.28 * k, y - r * 0.32 * k, rr, c)
    cv.circle(x - r * 0.34, y - r * 0.38, r * 0.14, A((255, 255, 255), 0.55))

def isobox(cv, cx, cy, a, b, h, col, outline=True):
    top = [(cx, cy - h - b), (cx + a, cy - h), (cx, cy - h + b), (cx - a, cy - h)]
    left = [(cx - a, cy - h), (cx, cy - h + b), (cx, cy + b), (cx - a, cy)]
    right = [(cx + a, cy - h), (cx, cy - h + b), (cx, cy + b), (cx + a, cy)]
    cv.poly(left, shade(col, 0.72)); cv.poly(right, shade(col, 0.5)); cv.poly(top, shade(col, 1.22))
    if outline:
        cv.line([top[0], top[1], top[2], top[3], top[0]], A((255, 255, 255), 0.18), 1.2)
    return left, right

