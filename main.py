def clean_script(d):
    sc = []
    top_bg = str(d.get("bg", "")).strip().lower()
    for i, s in enumerate(d.get("scenes", [])):
        raw = re.sub(r"[#*_\[\]{}<>|]", "", str(s.get("text", ""))).strip()
        text = TASHKEEL.sub("", raw).strip()
        if len(text.split()) < 3: continue
        layout = str(s.get("layout", s.get("motif", ""))).strip().lower()
        objs = [str(o).strip().lower() for o in (s.get("objects") or []) if isinstance(o, str)]
        objs = list(dict.fromkeys(o for o in objs if o in OBJ))[:4]
        if not objs and layout not in LEGACY_FN and layout != "counter":
            objs = keyword_objects(text)
        label = " ".join(TASHKEEL.sub("", str(s.get("label", ""))).strip().split()[:2])
        sc.append(dict(text=text, tts=raw, layout=layout, objs=objs, bg=str(s.get("bg", "")).strip().lower(), label=label,
                       value=str(s.get("value", "")).strip(), unit=str(s.get("unit", "")).strip()))
    if len(sc) < 5: raise ValueError("too few scenes")
    sc = sc[:11]
    cats = [OBJ[o][1] for s in sc for o in s["objs"]]
    default_theme = top_bg if top_bg in THEME_NAMES else (CAT_THEME[max(set(cats), key=cats.count)] if cats else "abstract")
    used_counter = False
    def fix(s, lay):
        theme = s["bg"] if s["bg"] in THEME_NAMES else default_theme
        if lay in LAYOUT_FN and not s["objs"]: s["objs"] = [THEME_OBJ.get(theme, "star")]
        n = len(s["objs"])
        if lay in ("chain", "versus") and n < 2: lay = "hero"
        if lay == "cycle" and n < 2: lay = "orbit"
        s["layout"], s["theme"] = lay, theme
    for i, s in enumerate(sc):
        lay = s["layout"] if s["layout"] in LAYOUTS else "hero"
        if lay == "counter":
            if used_counter or not re.search(r"\d", s["value"]): lay = "hero"
            else: used_counter = True
        fix(s, lay)
    flex = ["hero", "orbit", "chain", "cycle", "rain", "grow", "versus"]
    for i in range(1, len(sc)):
        if sc[i]["layout"] == sc[i - 1]["layout"]:
            nxt = sc[i + 1]["layout"] if i + 1 < len(sc) else ""
            for l in flex[i % len(flex):] + flex[:i % len(flex)]:
                if l != sc[i - 1]["layout"] and l != nxt:
                    fix(sc[i], l)
                    if sc[i]["layout"] != sc[i - 1]["layout"]: break
    title = TASHKEEL.sub("", str(d.get("title", "")).replace("#", "")).strip()[:90]
    if not title: raise ValueError("no title")
    tags = [str(t).strip()[:40] for t in d.get("tags", []) if str(t).strip()][:15]
    hashtags = [h if h.startswith("#") else "#" + h for h in [str(x).strip().replace(" ", "_") for x in d.get("hashtags", [])] if h][:5]
    desc = str(d.get("description", "")).strip()
    return dict(topic=str(d.get("topic", title))[:80], title=title, description=desc, tags=tags, hashtags=hashtags, scenes=sc)

def _norm_tokens(t):
    t = TASHKEEL.sub("", str(t))
    t = re.sub("[إأآ]", "ا", t).replace("ى", "ي").replace("ة", "ه")
    stop = {"كيف", "ماذا", "لماذا", "يعمل", "تعمل", "حقيقه", "داخل", "هذا", "هذه", "الذي", "التي", "اكثر", "بدون"}
    out = set()
    for w in re.findall(r"\w+", t):
        if w.startswith("ال") and len(w) > 4: w = w[2:]
        if len(w) >= 3 and w not in stop: out.add(w)
    return out

def is_dup(script, state):
    a, b = _norm_tokens(script["topic"]), _norm_tokens(script["title"])
    for u in state.get("used", []):
        ua, ub = _norm_tokens(u.get("topic", "")), _norm_tokens(u.get("title", ""))
        for x, y, th in ((a, ua, 0.5), (b, ub, 0.55), (a | b, ua | ub, 0.5)):
            if x and y and len(x & y) / len(x | y) >= th:
                return u.get("topic") or u.get("title")
        common = a & ua
        if len(common) >= 2 and len(common) >= 0.66 * min(len(a), len(ua)):
            return u.get("topic")
    return None

def write_script(state):
    rejected, errs = [], []
    for rnd in range(4):
        prompt = build_prompt(state, rejected)
        for fn in (ask_gemini, ask_openai):
            try:
                sc = clean_script(fn(prompt))
            except Exception as e:
                errs.append(f"{fn.__name__}: {e}"); log("script attempt failed:", e); time.sleep(4); continue
            dup = is_dup(sc, state)
            if dup:
                rejected.append(sc["topic"]); log("duplicate of:", dup, "-> asking for a new topic"); break
            attach_art(sc)
            return sc
    raise RuntimeError("no fresh script: " + " | ".join(errs[-4:]) + f" | rejected={rejected}")

