def _find_font():
    global _FONT_PATH
    if _FONT_PATH:
        return _FONT_PATH
    cands = []
    try:
        res = subprocess.run(["fc-list", ":lang=ar", "file"], capture_output=True, text=True).stdout
        cands = [l.split(":")[0].strip() for l in res.splitlines() if l.strip()]
    except Exception:
        pass
    cands += glob.glob("/usr/share/fonts/**/*.ttf", recursive=True)
    def score(p):
        n = os.path.basename(p).lower()
        s = 0
        if "notosansarabic" in n and "ui" not in n: s += 50
        if "kufi" in n: s += 40
        if "amiri" in n and "bold" in n and "quran" not in n: s += 20
        if "bold" in n: s += 15
        if "condensed" in n or "light" in n or "thin" in n or "semi" in n or "extra" in n: s -= 20
        if "dejavusans-bold" in n: s += 5
        return s
    cands = [c for c in cands if c.lower().endswith((".ttf", ".otf"))]
    cands.sort(key=score, reverse=True)
    _FONT_PATH = cands[0] if cands else None
    log("font:", _FONT_PATH)
    return _FONT_PATH

_FONTS = {}
def font(size):
    size = int(size)
    if size not in _FONTS:
        p = _find_font()
        eng = ImageFont.Layout.BASIC if _HAS_RESHAPER else ImageFont.Layout.RAQM
        try:
            _FONTS[size] = ImageFont.truetype(p, size, layout_engine=eng)
        except Exception:
            _FONTS[size] = ImageFont.truetype(p, size)
    return _FONTS[size]

def shape(t):
    if _HAS_RESHAPER:
        return get_display(arabic_reshaper.reshape(t))
    return t

_LATIN = {}
def latin_font(size):
    size = int(size)
    if size not in _LATIN:
        for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf"):
            if os.path.exists(p):
                _LATIN[size] = ImageFont.truetype(p, size); break
        else:
            _LATIN[size] = font(size)
    return _LATIN[size]

def draw_text(d, xy, text, size, fill, anchor="mm", stroke=0, stroke_fill=(0, 0, 0, 255), latin=False):
    if latin:
        d.text(xy, str(text), font=latin_font(size), fill=fill, anchor=anchor, stroke_width=stroke, stroke_fill=stroke_fill); return
    f = font(size)
    kw = {} if _HAS_RESHAPER else {"direction": "rtl"}
    try:
        d.text(xy, shape(text), font=f, fill=fill, anchor=anchor, stroke_width=stroke, stroke_fill=stroke_fill, **kw)
    except Exception:
        d.text(xy, shape(text), font=f, fill=fill, anchor=anchor, stroke_width=stroke, stroke_fill=stroke_fill)

def text_w(text, size):
    f = font(size)
    try:
        return f.getlength(shape(text))
    except Exception:
        return len(text) * size * 0.5

def wrap(text, size, maxw):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if text_w(t, size) <= maxw or not cur:
            cur = t
        else:
            lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines

