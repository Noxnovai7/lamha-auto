def render_svg_png(svg_text, px):
    """SVG text -> PIL RGBA (px x px). Uses rsvg-convert (apt: librsvg2-bin), falls back to cairosvg."""
    data = svg_text.encode("utf-8")
    exe = shutil.which("rsvg-convert")
    try:
        if exe:
            out = subprocess.run([exe, "-w", str(px), "-h", str(px), "-f", "png"], input=data, capture_output=True, timeout=60).stdout
            if out: return Image.open(io.BytesIO(out)).convert("RGBA")
    except Exception as e:
        log("rsvg-convert failed:", e)
    try:
        import cairosvg
        out = cairosvg.svg2png(bytestring=data, output_width=px, output_height=px)
        return Image.open(io.BytesIO(out)).convert("RGBA")
    except Exception as e:
        log("svg render unavailable:", e)
    return None

def sanitize_svg(txt):
    """Return a safe, well-formed <svg> string or None."""
    m = re.search(r"<svg\b.*</svg>", txt or "", re.S | re.I)
    if not m: return None
    svg = m.group(0)
    if len(svg) > 70000: return None
    svg = re.sub(r"<text\b.*?</text>", "", svg, flags=re.S | re.I)
    svg = re.sub(r"<(script|foreignObject|image|filter|style|animate\w*|set)\b.*?(</\1>|/>)", "", svg, flags=re.S | re.I)
    if re.search(r"(xlink:)?href\s*=\s*[\"'](?!#)", svg, re.I) or "@import" in svg or "javascript:" in svg.lower(): return None
    if "xmlns=" not in svg[:400]:
        svg = svg.replace("<svg", f'<svg xmlns="{SVG_NS}"', 1)
    if "viewBox" not in svg[:600]:
        svg = svg.replace("<svg", '<svg viewBox="0 0 400 400"', 1)
    svg = re.sub(r"&(?!(amp|lt|gt|quot|apos|#\d+);)", "&amp;", svg)
    try:
        ET.fromstring(svg)
    except Exception:
        return None
    return svg

def svg_layers(svg_text):
    """Split an SVG into animated layers. Returns list of dict(img, x, y, anim) or None if unusable."""
    svg = sanitize_svg(svg_text)
    if not svg: return None
    try:
        ET.register_namespace("", SVG_NS)
        root = ET.fromstring(svg)
        vb = [float(v) for v in re.split(r"[ ,]+", root.get("viewBox", "0 0 400 400").strip())]
        if len(vb) != 4 or vb[2] <= 0 or vb[3] <= 0: vb = [0, 0, 400, 400]
        defs, groups, loose = [], [], []
        for ch in list(root):
            tag = ch.tag.split("}")[-1]
            if tag in ("defs", "linearGradient", "radialGradient", "clipPath", "mask", "pattern", "symbol"): defs.append(ch)
            elif tag == "g": groups.append(ch)
            elif tag in ("circle", "ellipse", "rect", "path", "polygon", "polyline", "line"): loose.append(ch)
        if loose:
            g = ET.Element(f"{{{SVG_NS}}}g", {"id": "static-base"}); g.extend(loose); groups.insert(0, g)
        if not groups: return None
        groups = groups[:6]
        head = f'<svg xmlns="{SVG_NS}" viewBox="{vb[0]} {vb[1]} {vb[2]} {vb[3]}" preserveAspectRatio="xMidYMid meet">'
        defs_s = "".join(ET.tostring(d, encoding="unicode") for d in defs)
        px = ART * SS
        layers, cover = [], 0
        for i, g in enumerate(groups):
            gid = (g.get("id") or "").lower()
            anim = gid.split("-")[0] if gid.split("-")[0] in ANIMS else "float"
            doc = head + defs_s + ET.tostring(g, encoding="unicode") + "</svg>"
            im = render_svg_png(doc, px)
            if im is None: return None
            bb = im.getchannel("A").getbbox()
            if not bb: continue
            crop = im.crop(bb)
            cover += int(np.asarray(crop.getchannel("A")).astype(bool).sum())
            layers.append(dict(img=crop, x=bb[0], y=bb[1], anim=anim))
        if not layers or cover < 0.015 * px * px: return None
        return layers
    except Exception as e:
        log("svg layers failed:", e)
        return None

