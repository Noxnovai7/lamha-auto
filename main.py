def extract_json(txt):
    txt = txt.strip()
    txt = re.sub(r"^```(?:json)?|```$", "", txt, flags=re.M).strip()
    s, e = txt.find("{"), txt.rfind("}")
    return json.loads(txt[s:e + 1])

def gemini_models(key):
    r = requests.get("https://generativelanguage.googleapis.com/v1beta/models", params={"key": key, "pageSize": 200}, timeout=30)
    r.raise_for_status()
    out = []
    for m in r.json().get("models", []):
        n = m["name"].split("/")[-1]
        if "generateContent" not in m.get("supportedGenerationMethods", []): continue
        if "flash" not in n: continue
        if any(x in n for x in ("image", "tts", "audio", "live", "embedding", "learnlm", "gemma", "robotics", "computer", "vision")): continue
        v = re.search(r"gemini-(\d+(?:\.\d+)?)", n)
        out.append((-(float(v.group(1)) if v else 0), "lite" in n, "preview" in n or "exp" in n, n))
    out.sort()
    return [o[3] for o in out]

def ask_gemini(prompt, json_mode=True):
    key = os.getenv("GEMINI_API_KEY")
    if not key: raise RuntimeError("no GEMINI_API_KEY")
    models = gemini_models(key)[:6]
    log("gemini models:", models)
    last = None
    for m in models:
        for attempt in range(3):
            try:
                r = requests.post(f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent", params={"key": key},
                                  json={"contents": [{"parts": [{"text": prompt}]}], "generationConfig": ({"temperature": 0.95, "responseMimeType": "application/json"} if json_mode else {"temperature": 0.8, "maxOutputTokens": 30000})}, timeout=240)
                if r.status_code == 404: last = f"{m} 404"; break
                if r.status_code in (429, 500, 502, 503, 504):
                    last = f"{m} {r.status_code}"; time.sleep(6 * (attempt + 1)); continue
                r.raise_for_status()
                txt = "".join(p.get("text", "") for p in r.json()["candidates"][0]["content"]["parts"])
                if not json_mode:
                    if "<svg" not in txt: raise ValueError("no svg in reply")
                    return txt
                return extract_json(txt)
            except Exception as e:
                last = f"{m}: {e}"; time.sleep(3)
    raise RuntimeError(f"gemini failed: {last}")

