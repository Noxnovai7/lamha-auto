def render_frame(sc, tl, gt, total, caption=True):
    pal = sc.pal
    bg = get_bg(sc.theme, pal, sc.var).copy()
    cv = Cv(bg)
    ambient(cv, gt, sc.theme, pal, sc.seed)
    try:
        if sc.layout == "end":
            pass
        elif getattr(sc, "art", None):
            draw_art(cv, tl, sc.art, pal)
        elif sc.layout == "counter":
            m_counter(cv, tl, pal, sc.seed, sc.value, sc.unit)
        elif sc.layout in LAYOUT_FN:
            LAYOUT_FN[sc.layout](cv, tl, pal, sc.seed, sc.objs)
        else:
            LEGACY_FN[sc.layout](cv, tl, pal, sc.seed)
    except Exception as e:
        if not getattr(sc, "_warned", False):
            log("scene draw error:", sc.layout, sc.objs, repr(e)); sc._warned = True
    prog = min(1.0, tl / max(sc.dur, 0.1))
    punch = 0.10 * math.exp(-tl * 7.5)
    cam = getattr(sc, "cam", 0)
    if cam == 0: zoom, dx = 1.0 + punch + 0.05 * prog, math.sin(tl * 0.6 + sc.seed) * 7
    elif cam == 1: zoom, dx = 1.07 + punch - 0.05 * prog, math.sin(tl * 0.6 + sc.seed) * 7
    else: zoom, dx = 1.04 + punch, (prog - 0.5) * 50 * (1 if sc.idx % 2 else -1)
    cx, cy = W / 2 + dx, H * 0.47
    bw, bh = W * SS / zoom, H * SS / zoom
    x0 = clamp(cx * SS - bw / 2, 0, W * SS - bw); y0 = clamp(cy * SS - bh / 2, 0, H * SS - bh)
    img = bg.resize((W, H), Image.BILINEAR, box=(x0, y0, x0 + bw, y0 + bh))
    d = ImageDraw.Draw(img, "RGBA")
    fl = 0.30 * math.exp(-tl * 16)
    if fl > 0.01 and sc.idx > 0:
        d.rectangle([0, 0, W, H], fill=(255, 255, 255, int(255 * fl)))
    if sc.layout == "end":
        k = eob(tl / 0.7); s = max(0.05, k)
        lg = logo_big(max(8, int(380 * s)))
        img.paste(lg, (int(W / 2 - lg.width / 2), int(H * 0.36 - lg.height / 2)), lg)
        draw_text(d, (W / 2, H * 0.55), CHANNEL, 150, A(GOLD, clamp(tl / 0.5)), "mm")
        draw_text(d, (W / 2, H * 0.64), "تابعنا لمعلومة جديدة كل يوم", 46, A((255, 255, 255), clamp((tl - 0.3) / 0.5)), "mm")
    else:
        render_label(img, sc.label, tl - 0.35, pal)
        if caption:
            cur = None
            for i, (s0, s1, w) in enumerate(sc.words):
                if tl >= s0: cur = (i, s0, w)
            if cur and tl < sc.dur - 0.05:
                render_caption(img, cur[2], tl - cur[1], cur[0] % 3 == 2, pal)
    # progress bar + watermark
    d.rounded_rectangle([20, 18, W - 20, 26], radius=4, fill=(255, 255, 255, 50))
    d.rounded_rectangle([20, 18, 20 + (W - 40) * clamp(gt / total), 26], radius=4, fill=pal["acc"] + (255,))
    lg = logo_small()
    img.paste(lg, (22, 40), lg)
    return img

