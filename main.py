def _trim(audio, ev):
    env = np.convolve(np.abs(audio), np.ones(int(0.02 * SR), np.float32) / int(0.02 * SR), mode="same")
    idx = np.where(env > env.max() * 0.04)[0]
    if len(idx) == 0: return audio, ev
    a, b = max(0, idx[0] - int(0.04 * SR)), min(len(audio), idx[-1] + int(0.10 * SR))
    return audio[a:b], [(max(0.0, o - a / SR), d) for o, d in ev]

def tts_scene(text, path):
    global _CUR_VOICE
    last = None
    cands = [_CUR_VOICE] if _CUR_VOICE else voice_candidates()
    for voice in cands:
        tries = 3 if (not _LISTED or voice in _LISTED or voice == _CUR_VOICE) else 1
        for attempt in range(tries):
            try:
                ev = asyncio.run(_tts_async(text, voice, path))
                if os.path.getsize(path) < 2000: raise RuntimeError("empty audio")
                audio = _ffmpeg_decode(path)
                if len(audio) / SR < 0.12 * len(text.split()): raise RuntimeError("audio too short")
                if _CUR_VOICE != voice: log("voice:", voice)
                _CUR_VOICE = voice
                audio, ev = _trim(audio, ev)
                return audio, ev
            except Exception as e:
                last = e; log("tts retry:", voice, e)
                if tries > 1: time.sleep(2 + attempt * 2)
    raise RuntimeError(f"tts failed: {last}")

def word_timings(text, ev, dur, audio=None):
    words = text.split()
    n = len(words)
    if ev and len(ev) >= max(2, int(n * 0.6)):
        starts = [ev[min(len(ev) - 1, int(i * len(ev) / n))][0] for i in range(n)]
    else:
        t0, t1 = 0.05, max(0.5, dur - 0.1)
        env = None
        if audio is not None and len(audio) > SR // 5:
            env = np.convolve(np.abs(audio), np.ones(int(0.02 * SR), np.float32) / int(0.02 * SR), mode="same")
            idx = np.where(env > env.max() * 0.06)[0]
            if len(idx): t0, t1 = idx[0] / SR, idx[-1] / SR
        wts = [max(2, len(w)) for w in words]; tot = float(sum(wts)); acc = 0.0; starts = []
        for w in wts:
            starts.append(t0 + acc / tot * (t1 - t0)); acc += w
        if env is not None:
            for i in range(1, n):
                a, b = int(max(0.0, starts[i] - 0.12) * SR), int(min(dur, starts[i] + 0.12) * SR)
                if b - a > 10: starts[i] = (a + int(np.argmin(env[a:b]))) / SR
            starts = sorted(starts)
    starts = [min(x, dur - 0.1) for x in starts]
    out = []
    for i, w in enumerate(words):
        out.append((starts[i], starts[i + 1] if i + 1 < n else dur, w))
    return out

