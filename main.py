def build_video(script, workdir=OUT, tts=tts_scene, seed=None):
    os.makedirs(workdir, exist_ok=True)
    seed = seed if seed is not None else int(time.time())
    rng = random.Random(seed)
    scenes, voice_parts, t0 = [], [], 0.0
    for i, s in enumerate(script["scenes"]):
        sc = Scene()
        audio, ev = tts(s.get("tts") or s["text"], os.path.join(workdir, f"v{i}.mp3"))
        vlen = len(audio) / SR
        sc.idx, sc.text, sc.layout, sc.objs, sc.label, sc.value, sc.unit = i, s["text"], s["layout"], s.get("objs", []), s["label"], s["value"], s["unit"]
        sc.theme, sc.cam, sc.var = s["theme"], i % 3, i
        sc.art = svg_layers(s["svg"]) if s.get("svg") and s["layout"] != "counter" else None
        sc.dur = vlen + 0.34
        sc.t0 = t0; sc.seed = rng.randint(1, 10 ** 6); sc.pal = theme_palette(sc.theme, rng.randint(0, 5))
        sc.words = word_timings(s["text"], ev, vlen, audio)
        scenes.append(sc); voice_parts.append((t0, audio)); t0 += sc.dur
    log("scenes with AI drawing:", sum(1 for x in scenes if getattr(x, "art", None)), "of", len(scenes))
    end = Scene(); end.idx, end.layout, end.objs, end.label, end.value, end.unit, end.words, end.text = len(scenes), "end", [], "", "", "", [], ""
    end.dur, end.t0, end.seed, end.theme, end.pal, end.var, end.cam, end.art = 2.2, t0, 11, "abstract", PALETTES[0], 0, 0, None
    scenes.append(end); D = t0 + end.dur
    log(f"scenes={len(scenes)-1} duration={D:.1f}s")
    voice = np.zeros(int(D * SR) + SR, np.float32)
    for st, a in voice_parts:
        s = int(st * SR); voice[s:s + len(a)] += a
    events = []
    for sc in scenes[:-1]:
        events.append((sc.t0 - 0.02, "whoosh"))
        if sc.label: events.append((sc.t0 + 0.35, "pop"))
        for (w0, w1, w) in sc.words: events.append((sc.t0 + w0, "tick"))
    events.append((end.t0 + 0.1, "chime")); events.append((end.t0 + 0.0, "whoosh"))
    mix = mix_audio(voice, D, events, seed)
    wav = os.path.join(workdir, "mix.wav"); write_wav(wav, mix)
    video = os.path.join(workdir, "video.mp4"); thumb = os.path.join(workdir, "thumb.jpg")
    cmd = ["ffmpeg", "-y", "-v", "error", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{W}x{H}", "-r", str(FPS), "-i", "-",
           "-i", wav, "-vf", "scale=1080:1920:flags=lanczos", "-c:v", "libx264", "-preset", "veryfast", "-crf", "19", "-pix_fmt", "yuv420p",
           "-c:a", "aac", "-b:a", "160k", "-ac", "2", "-movflags", "+faststart", "-shortest", video]
    proc = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    nframes = int(D * FPS)
    si = 0
    t_start = time.time()
    for f in range(nframes):
        gt = f / FPS
        while si < len(scenes) - 1 and gt >= scenes[si].t0 + scenes[si].dur: si += 1
        sc = scenes[si]
        img = render_frame(sc, gt - sc.t0, gt, D)
        proc.stdin.write(img.tobytes())
        if f % 150 == 0: log(f"frame {f}/{nframes}  {time.time()-t_start:.0f}s")
    proc.stdin.close(); proc.wait()
    if proc.returncode != 0: raise RuntimeError("ffmpeg failed")
    try:
        sc0 = scenes[0]
        t_img = render_frame(sc0, 1.1, 1.1, D, caption=False)
        d = ImageDraw.Draw(t_img, "RGBA")
        d.rectangle([0, int(H * 0.52), W, int(H * 0.86)], fill=(8, 12, 30, 170))
        tsz = 70
        lines = wrap(script["title"], tsz, W * 0.88)
        while len(lines) > 3 and tsz > 40:
            tsz -= 4; lines = wrap(script["title"], tsz, W * 0.88)
        y = H * 0.69 - (len(lines) - 1) * tsz * 0.63
        for ln in lines:
            draw_text(d, (W / 2, y), ln, tsz, (255, 255, 255, 255), "mm", stroke=6, stroke_fill=(8, 12, 30, 255)); y += tsz * 1.26
        t_img.convert("RGB").resize((1080, 1920), Image.LANCZOS).save(thumb, quality=88)
    except Exception as e:
        log("thumb failed:", e); thumb = None
    return video, thumb, D

