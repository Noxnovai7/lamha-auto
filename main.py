def _env_decay(n, rate): return np.exp(-np.arange(n) / SR * rate).astype(np.float32)

def sfx_whoosh(dur=0.6, seed=1):
    rng = np.random.default_rng(seed)
    n = int(dur * SR); noise = rng.standard_normal(n).astype(np.float32)
    out = np.zeros(n, np.float32); y = 0.0
    for i in range(n):
        a = 0.015 + 0.55 * (i / n) ** 1.6
        y += a * (noise[i] - y); out[i] = y
    env = np.sin(np.pi * np.arange(n) / n) ** 2
    out = out * env; return out / (np.max(np.abs(out)) + 1e-6) * 0.7

def sfx_pop():
    n = int(0.18 * SR); tau = np.arange(n) / SR
    f = 320 + 700 * np.exp(-tau * 22)
    return (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-tau * 26)).astype(np.float32) * 0.8

def sfx_tick():
    n = int(0.09 * SR); tau = np.arange(n) / SR
    return (np.sin(2 * np.pi * 85 * tau) * np.exp(-tau * 38) * 0.9 + np.sin(2 * np.pi * 1800 * tau) * np.exp(-tau * 160) * 0.25).astype(np.float32)

def sfx_chime():
    out = np.zeros(int(1.4 * SR), np.float32)
    for i, f in enumerate((523.25, 659.25, 783.99, 1046.5)):
        n = int(1.0 * SR); tau = np.arange(n) / SR
        s = (np.sin(2 * np.pi * f * tau) + 0.3 * np.sin(2 * np.pi * 2 * f * tau)) * np.exp(-tau * 4.5) * 0.35
        st = int(i * 0.11 * SR); out[st:st + n] += s[: len(out) - st]
    return out

def make_music(D, seed):
    rng = random.Random(seed)
    n = int(D * SR); t = np.arange(n, dtype=np.float32) / SR
    bpm = rng.choice([96, 100, 104, 108]); beat = 60.0 / bpm; bar = beat * 4
    progs = [
        [(220.0, 261.63, 329.63), (174.61, 220.0, 261.63), (261.63, 329.63, 392.0), (196.0, 246.94, 293.66)],
        [(196.0, 233.08, 293.66), (155.56, 196.0, 233.08), (233.08, 293.66, 349.23), (174.61, 220.0, 261.63)],
        [(164.81, 196.0, 246.94), (130.81, 164.81, 196.0), (196.0, 246.94, 293.66), (146.83, 185.0, 220.0)],
    ]
    prog = rng.choice(progs)
    out = np.zeros(n, np.float32)
    nb = int(D / bar) + 2
    for b in range(nb):
        ch = prog[b % 4]; s0 = int(b * bar * SR)
        if s0 >= n: break
        ln = min(int(bar * SR), n - s0)
        tau = np.arange(ln, dtype=np.float32) / SR
        env = np.minimum(1, tau / 0.4) * np.minimum(1, (bar - tau) / 0.3)
        for f in ch:
            out[s0:s0 + ln] += 0.05 * env * (np.sin(2 * np.pi * f * tau) + 0.5 * np.sin(2 * np.pi * f * 1.003 * tau + 1.3))
        # bass on each beat
        for q in range(4):
            bs = s0 + int(q * beat * SR)
            if bs >= n: break
            m = min(int(beat * SR), n - bs); tt = np.arange(m, dtype=np.float32) / SR
            fr = ch[0] / 2
            out[bs:bs + m] += 0.26 * np.exp(-tt * 5) * (np.sin(2 * np.pi * fr * tt) + 0.3 * np.sin(2 * np.pi * 2 * fr * tt))
            # kick
            kk = min(int(0.3 * SR), n - bs); kt = np.arange(kk, dtype=np.float32) / SR
            ph = 2 * np.pi * (45 * kt + 110 / 25 * (1 - np.exp(-25 * kt)))
            out[bs:bs + kk] += 0.38 * np.sin(ph) * np.exp(-kt * 9)
        # arp 8ths
        for q in range(8):
            as_ = s0 + int(q * beat / 2 * SR)
            if as_ >= n: break
            m = min(int(0.25 * SR), n - as_); tt = np.arange(m, dtype=np.float32) / SR
            fr = ch[(q * 2) % 3] * 2
            out[as_:as_ + m] += 0.045 * np.exp(-tt * 14) * np.sin(2 * np.pi * fr * tt)
            if q % 2 == 1:  # hat
                hs = np.random.default_rng(b * 8 + q).standard_normal(m).astype(np.float32)
                hs = np.diff(hs, prepend=0)
                out[as_:as_ + m] += 0.05 * hs * np.exp(-tt * 70)
    out /= (np.max(np.abs(out)) + 1e-6)
    return out * 0.9

def smooth_env(x, win):
    k = np.ones(win, np.float32) / win
    return np.convolve(np.abs(x), k, mode="same")

def mix_audio(voice, D, events, seed):
    n = int(D * SR)
    voice = np.pad(voice, (0, max(0, n - len(voice))))[:n]
    pk = np.max(np.abs(voice)) + 1e-6
    voice = voice / pk * 0.92
    music = make_music(D, seed)
    env = smooth_env(voice, int(0.06 * SR)); env = env / (env.max() + 1e-6)
    duck = 1 - 0.62 * np.clip(env * 5, 0, 1)
    duck = np.convolve(duck, np.ones(int(0.2 * SR), np.float32) / int(0.2 * SR), mode="same")
    fade = np.minimum(1, np.arange(n) / SR / 0.8) * np.minimum(1, (D - np.arange(n) / SR) / 1.2)
    sfx = np.zeros(n, np.float32)
    cache = {"whoosh": [sfx_whoosh(0.6, s) for s in (1, 2, 3)], "pop": [sfx_pop()], "tick": [sfx_tick()], "chime": [sfx_chime()]}
    gains = {"whoosh": 0.55, "pop": 0.55, "tick": 0.16, "chime": 0.5}
    for i, (tt, kind) in enumerate(events):
        arr = cache[kind][i % len(cache[kind])]
        st = int(tt * SR)
        if st < 0 or st >= n: continue
        e = min(len(arr), n - st)
        sfx[st:st + e] += arr[:e] * gains[kind]
    mix = voice + music * 0.30 * duck * fade + sfx
    mix = np.tanh(mix * 1.1) * 0.92
    return mix

def write_wav(path, x):
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype(np.int16).tobytes())

