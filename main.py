def _gear_pts(cx, cy, r, teeth, rot, depth=0.17):
    pts = []
    for i in range(teeth * 4):
        a = rot + i * 2 * math.pi / (teeth * 4)
        rr = r * (1 + depth) if (i % 4) in (1, 2) else r
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    return pts

